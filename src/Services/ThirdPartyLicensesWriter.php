<?php

namespace EgyptDevRu\FilamentProjectPassport\Services;

use Illuminate\Support\Facades\File;

/**
 * Writes base_path('THIRD-PARTY-LICENSES.txt') from Composer + NPM open-source license scans.
 */
final class ThirdPartyLicensesWriter
{
    public const string FILENAME = 'THIRD-PARTY-LICENSES.txt';

    /**
     * Refresh open-source license caches when needed and rewrite the host-app file.
     *
     * @return array{path: string, packages: int}
     */
    public function refresh(bool $fresh = false): array
    {
        $composer = app(ComposerOpenSourceLicensesAuditor::class)->audit(fresh: $fresh);
        $npm = app(NpmOpenSourceLicensesAuditor::class)->audit(fresh: $fresh);

        return $this->write($composer['packages'], $npm['packages']);
    }

    /**
     * @param  list<array<string, mixed>>  $composerPackages
     * @param  list<array<string, mixed>>  $npmPackages
     * @return array{path: string, packages: int}
     */
    public function write(array $composerPackages, array $npmPackages): array
    {
        $entries = [];

        foreach ($composerPackages as $package) {
            $entries[] = $this->formatEntry($package, 'Composer');
        }

        foreach ($npmPackages as $package) {
            $entries[] = $this->formatEntry($package, 'NPM');
        }

        usort(
            $entries,
            fn (array $a, array $b): int => strcasecmp($a['sort'], $b['sort'])
        );

        $lines = [
            'THIRD-PARTY LICENSES',
            'Generated by EgyptDevRu Filament Project Passport.',
            'This file lists open-source package licenses used by this application.',
            'Generated at: '.now()->toIso8601String(),
            '',
        ];

        foreach ($entries as $entry) {
            $lines[] = $entry['body'];
        }

        if ($entries === []) {
            $lines[] = str_repeat('=', 80);
            $lines[] = 'No third-party packages with license metadata were found.';
            $lines[] = str_repeat('=', 80);
            $lines[] = '';
        }

        $path = base_path(self::FILENAME);
        File::put($path, implode("\n", $lines));

        return [
            'path' => $path,
            'packages' => count($entries),
        ];
    }

    /**
     * @param  array<string, mixed>  $package
     * @return array{sort: string, body: string}
     */
    private function formatEntry(array $package, string $ecosystem): array
    {
        $name = (string) ($package['name'] ?? '');
        $license = (string) ($package['license_label'] ?? 'Unknown');
        $version = (string) ($package['version'] ?? '—');
        $text = trim((string) ($package['license_text'] ?? ''));

        if ($text === '') {
            $text = 'No LICENSE file text was available for this package.';

            if ($license !== 'Unknown') {
                $text .= " Declared license: {$license}.";
            }
        }

        $delimiter = str_repeat('=', 80);
        $rule = str_repeat('-', 80);

        $body = implode("\n", [
            $delimiter,
            "Package: {$name}",
            "Ecosystem: {$ecosystem}",
            "Version: {$version}",
            "License: {$license}",
            $rule,
            $text,
            $delimiter,
            '',
        ]);

        return [
            'sort' => $ecosystem.' '.$name,
            'body' => $body,
        ];
    }
}
